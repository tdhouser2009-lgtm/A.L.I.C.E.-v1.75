from __future__ import annotations

import threading
import tkinter as tk
from pathlib import Path
from tkinter import filedialog, messagebox, ttk
from typing import Callable

DEFAULT_CHECKPOINT = Path.home() / ".local-model" / "tiny-transformer.pt"


class LocalModelApp:
    def __init__(self, root: tk.Tk) -> None:
        self.root = root
        self.root.title("From-Scratch Local Model")
        self.root.geometry("900x700")
        self.root.minsize(680, 520)
        self.checkpoint_path = tk.StringVar(value=str(DEFAULT_CHECKPOINT))
        self.corpus_path = tk.StringVar()
        self.steps = tk.StringVar(value="500")
        self.max_tokens = tk.StringVar(value="200")
        self.busy = False
        self._build_ui()

    def _build_ui(self) -> None:
        self.root.columnconfigure(0, weight=1)
        self.root.rowconfigure(2, weight=1)
        self.root.rowconfigure(3, weight=1)

        model_frame = ttk.LabelFrame(self.root, text="Local model checkpoint")
        model_frame.grid(row=0, column=0, sticky="ew", padx=10, pady=(10, 5))
        model_frame.columnconfigure(1, weight=1)
        ttk.Label(model_frame, text="Checkpoint").grid(
            row=0, column=0, sticky="w", padx=6, pady=6
        )
        ttk.Entry(model_frame, textvariable=self.checkpoint_path).grid(
            row=0, column=1, sticky="ew", padx=6, pady=6
        )
        ttk.Button(model_frame, text="Choose", command=self._choose_checkpoint).grid(
            row=0, column=2, padx=6, pady=6
        )
        self.initialize_button = ttk.Button(
            model_frame, text="Create random model", command=self._initialize_model
        )
        self.initialize_button.grid(row=0, column=3, padx=6, pady=6)

        training = ttk.LabelFrame(self.root, text="Train locally from text and code")
        training.grid(row=1, column=0, sticky="ew", padx=10, pady=5)
        training.columnconfigure(1, weight=1)
        ttk.Label(training, text="Corpus file or folder").grid(
            row=0, column=0, sticky="w", padx=6, pady=6
        )
        ttk.Entry(training, textvariable=self.corpus_path).grid(
            row=0, column=1, sticky="ew", padx=6, pady=6
        )
        ttk.Button(training, text="Choose file", command=self._choose_corpus_file).grid(
            row=0, column=2, padx=3, pady=6
        )
        ttk.Button(training, text="Choose folder", command=self._choose_corpus_folder).grid(
            row=0, column=3, padx=3, pady=6
        )
        ttk.Label(training, text="Training steps").grid(
            row=1, column=0, sticky="w", padx=6, pady=(0, 6)
        )
        ttk.Entry(training, textvariable=self.steps, width=10).grid(
            row=1, column=1, sticky="w", padx=6, pady=(0, 6)
        )
        self.train_button = ttk.Button(
            training, text="Train / continue training", command=self._train
        )
        self.train_button.grid(row=1, column=3, sticky="e", padx=6, pady=(0, 6))

        generation = ttk.LabelFrame(self.root, text="Prompt continuation")
        generation.grid(row=2, column=0, sticky="nsew", padx=10, pady=5)
        generation.columnconfigure(0, weight=1)
        generation.rowconfigure(1, weight=1)
        ttk.Label(
            generation,
            text=(
                "This model continues raw text; it is not an instruction-tuned chatbot. "
                "Prompts can contain code or other text."
            ),
        ).grid(row=0, column=0, columnspan=2, sticky="w", padx=6, pady=(6, 2))
        self.prompt = tk.Text(generation, height=5, wrap=tk.WORD)
        self.prompt.grid(row=1, column=0, columnspan=2, sticky="nsew", padx=6, pady=4)
        ttk.Label(generation, text="New bytes").grid(
            row=2, column=0, sticky="w", padx=6, pady=6
        )
        ttk.Entry(generation, textvariable=self.max_tokens, width=10).grid(
            row=2, column=0, sticky="w", padx=(80, 6), pady=6
        )
        self.generate_button = ttk.Button(
            generation, text="Generate continuation", command=self._generate
        )
        self.generate_button.grid(row=2, column=1, sticky="e", padx=6, pady=6)

        output_frame = ttk.LabelFrame(self.root, text="Generated bytes decoded as UTF-8")
        output_frame.grid(row=3, column=0, sticky="nsew", padx=10, pady=5)
        output_frame.columnconfigure(0, weight=1)
        output_frame.rowconfigure(0, weight=1)
        self.output = tk.Text(output_frame, wrap=tk.WORD, state=tk.DISABLED)
        self.output.grid(row=0, column=0, sticky="nsew", padx=6, pady=6)
        ttk.Button(
            output_frame, text="Save output", command=self._save_output
        ).grid(row=1, column=0, sticky="e", padx=6, pady=(0, 6))

        self.status = tk.StringVar(value="No model loaded. Create a random model or train.")
        ttk.Label(self.root, textvariable=self.status, anchor="w").grid(
            row=4, column=0, sticky="ew", padx=12, pady=(0, 8)
        )

    def _choose_checkpoint(self) -> None:
        path = filedialog.asksaveasfilename(
            parent=self.root,
            title="Choose model checkpoint",
            initialfile=Path(self.checkpoint_path.get()).name,
            defaultextension=".pt",
            filetypes=[("PyTorch checkpoint", "*.pt"), ("All files", "*")],
        )
        if path:
            self.checkpoint_path.set(path)

    def _choose_corpus_file(self) -> None:
        path = filedialog.askopenfilename(
            parent=self.root,
            title="Choose a text or code corpus",
            filetypes=[
                ("Text and source files", "*.txt *.md *.py *.js *.ts *.json *.html *.css"),
                ("All files", "*"),
            ],
        )
        if path:
            self.corpus_path.set(path)

    def _choose_corpus_folder(self) -> None:
        path = filedialog.askdirectory(parent=self.root, title="Choose a corpus folder")
        if path:
            self.corpus_path.set(path)

    def _set_busy(self, busy: bool, status: str) -> None:
        self.busy = busy
        state = tk.DISABLED if busy else tk.NORMAL
        self.initialize_button.configure(state=state)
        self.train_button.configure(state=state)
        self.generate_button.configure(state=state)
        self.status.set(status)

    def _run_background(
        self,
        operation: Callable[[], str],
        success: Callable[[str], None],
    ) -> None:
        def worker() -> None:
            try:
                message = operation()
            except (OSError, RuntimeError, ValueError) as error:
                self.root.after(0, self._show_error, str(error))
                return
            self.root.after(0, success, message)

        threading.Thread(target=worker, daemon=True).start()

    def _show_error(self, message: str) -> None:
        self._set_busy(False, "Operation failed")
        messagebox.showerror("Local model", message, parent=self.root)

    def _initialize_model(self) -> None:
        if self.busy:
            return
        path = Path(self.checkpoint_path.get()).expanduser()
        if path.exists() and not messagebox.askyesno(
            "Replace checkpoint?",
            f"A file already exists at:\n{path}\n\nReplace it with a fresh random model?",
            parent=self.root,
        ):
            return

        def initialize() -> str:
            from local_model import ModelConfig, create_random_model, save_model

            save_model(create_random_model(ModelConfig()), path)
            return f"Saved a randomly initialized model to {path}"

        self._set_busy(True, "Initializing random model...")
        self._run_background(initialize, lambda message: self._set_busy(False, message))

    def _train(self) -> None:
        if self.busy:
            return
        try:
            steps = int(self.steps.get())
        except ValueError:
            messagebox.showerror("Invalid steps", "Training steps must be an integer.", parent=self.root)
            return
        source = Path(self.corpus_path.get()).expanduser()
        checkpoint = Path(self.checkpoint_path.get()).expanduser()
        self._set_busy(True, "Preparing local training...")

        def progress(step: int, loss: float) -> None:
            if step == 1 or step % 10 == 0:
                self.root.after(
                    0,
                    self.status.set,
                    f"Training step {step}/{steps} - loss {loss:.3f}",
                )

        def train() -> str:
            from local_model import train_model

            loss = train_model(source, checkpoint, steps=steps, progress=progress)
            return f"Training complete - final loss {loss:.3f}. Saved to {checkpoint}"

        self._run_background(train, lambda message: self._set_busy(False, message))

    def _generate(self) -> None:
        if self.busy:
            return
        try:
            max_tokens = int(self.max_tokens.get())
        except ValueError:
            messagebox.showerror(
                "Invalid length", "New bytes must be a whole number.", parent=self.root
            )
            return
        if max_tokens < 0 or max_tokens > 4000:
            messagebox.showerror(
                "Invalid length",
                "Choose a value from 0 to 4000 new bytes.",
                parent=self.root,
            )
            return
        prompt = self.prompt.get("1.0", tk.END).rstrip("\n")
        checkpoint = Path(self.checkpoint_path.get()).expanduser()

        def generate() -> str:
            from local_model import load_model

            model = load_model(checkpoint)
            return model.generate(prompt, max_new_tokens=max_tokens)

        self._set_busy(True, "Generating locally...")

        def show_result(result: str) -> None:
            self.output.configure(state=tk.NORMAL)
            self.output.delete("1.0", tk.END)
            self.output.insert("1.0", result)
            self.output.configure(state=tk.DISABLED)
            self._set_busy(False, "Generation complete")

        self._run_background(generate, show_result)

    def _save_output(self) -> None:
        output = self.output.get("1.0", tk.END).rstrip("\n")
        if not output:
            messagebox.showinfo("Nothing to save", "Generate some output first.", parent=self.root)
            return
        path = filedialog.asksaveasfilename(
            parent=self.root,
            title="Save generated text",
            initialfile="generated.txt",
            defaultextension=".txt",
        )
        if not path:
            return
        try:
            Path(path).write_text(output, encoding="utf-8")
        except OSError as error:
            messagebox.showerror("Could not save output", str(error), parent=self.root)
            return
        self.status.set(f"Saved output to {path}")


def main() -> None:
    try:
        import local_model  # noqa: F401
    except ModuleNotFoundError as error:
        if error.name != "torch":
            raise
        root = tk.Tk()
        root.withdraw()
        messagebox.showerror(
            "PyTorch required",
            "Install the CPU version of PyTorch first:\n\npython -m pip install -r requirements.txt",
            parent=root,
        )
        root.destroy()
        return

    root = tk.Tk()
    LocalModelApp(root)
    root.mainloop()


if __name__ == "__main__":
    main()
